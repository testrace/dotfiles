#!/usr/bin/env bash

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMP_DIR="$(mktemp -d)"
FAKE_BIN_DIR="$TMP_DIR/bin"

cleanup() {
  rm -rf "$TMP_DIR"
}

trap cleanup EXIT

mkdir -p "$FAKE_BIN_DIR"

# FAKE_STATE=fresh: 아무것도 설치되지 않은 새 Mac
# FAKE_STATE=done:  이미 모두 설치된 Mac
cat > "$FAKE_BIN_DIR/stow" <<'EOF'
#!/usr/bin/env bash
if [[ -d "$HOME/.config/herdr" && ! -L "$HOME/.config/herdr" ]]; then
  echo "stow $* (dir ready)" >> "$COMMAND_LOG"
  ln -sfn /repo/herdr/.config/herdr/config.toml "$HOME/.config/herdr/config.toml"
else
  echo "stow $* (dir missing)" >> "$COMMAND_LOG"
fi
EOF

cat > "$FAKE_BIN_DIR/herdr" <<'EOF'
#!/usr/bin/env bash
# 실제 herdr처럼 출력을 길게 이어서, 앞부분만 읽고 끝나는 파이프(SIGPIPE) 문제를 잡아낸다
pad() { for _ in $(seq 1 3000); do echo "other: not installed"; done; }
case "$1 $2" in
  "plugin list")
    # 사용법: herdr plugin list --plugin <id> --json
    if [[ "$FAKE_STATE" == done || ( "$FAKE_STATE" == tsk-missing && "$4" == herdr-file-viewer ) ]]; then
      echo '{"id":"cli:plugin","result":{"plugins":[{"plugin_id":"'"$4"'"}],"type":"plugin_list"}}'
    else
      echo '{"id":"cli:plugin","result":{"plugins":[],"type":"plugin_list"}}'
    fi
    pad
    ;;
  "plugin install")
    echo "herdr $*" >> "$COMMAND_LOG"
    ;;
  "integration status")
    if [[ "$FAKE_STATE" != fresh ]]; then
      echo "claude: current (v11) ($HOME/.claude/hooks/herdr-agent-state.sh)"
    else
      echo "claude: not installed ($HOME/.claude/hooks/herdr-agent-state.sh)"
    fi
    pad
    ;;
  "integration install")
    echo "herdr $*" >> "$COMMAND_LOG"
    ;;
  *)
    echo "unexpected herdr command: $*" >&2
    exit 98
    ;;
esac
EOF

cat > "$FAKE_BIN_DIR/tsk" <<'EOF'
#!/usr/bin/env bash
case "$*" in
  "setup herdr")
    config="$HOME/.config/herdr/config.toml"
    if [[ -L "$config" ]]; then
      echo "tsk setup: cannot open $config (symlinks/non-directories refused)" >&2
      exit 1
    fi
    echo "tsk $*" >> "$COMMAND_LOG"
    mkdir -p "$(dirname "$config")"
    echo '# generated by tsk' > "$config"
    ;;
  "setup claude")
    echo "tsk $*" >> "$COMMAND_LOG"
    if [[ "$FAKE_STATE" != fresh ]]; then
      echo "tsk setup: skill-exists" >&2
      exit 1
    fi
    ;;
  *)
    echo "unexpected tsk command: $*" >&2
    exit 98
    ;;
esac
EOF

chmod +x "$FAKE_BIN_DIR"/*

failures=0

run_case() {
  local name="$1" state="$2" expected_status="$3" expected_log="$4"
  local home="$TMP_DIR/home-$name"
  local log="$TMP_DIR/$name.log"
  mkdir -p "$home"
  : > "$log"

  if [[ -n "${5:-}" ]]; then
    "$5" "$home"
  fi

  local status=0
  PATH="$FAKE_BIN_DIR:$PATH" HOME="$home" FAKE_STATE="$state" COMMAND_LOG="$log" \
    bash "$ROOT_DIR/herdr-setup.sh" > "$TMP_DIR/$name.out" 2>&1 || status=$?

  local actual_log
  actual_log="$(cat "$log")"

  if [[ "$status" != "$expected_status" || "$actual_log" != "$expected_log" ]]; then
    failures=$((failures + 1))
    echo "FAIL: $name" >&2
    echo "  expected exit $expected_status, got $status" >&2
    echo "  expected commands:" >&2
    printf '%s\n' "$expected_log" | sed 's/^/    /' >&2
    echo "  actual commands:" >&2
    printf '%s\n' "$actual_log" | sed 's/^/    /' >&2
    echo "  script output:" >&2
    sed 's/^/    /' "$TMP_DIR/$name.out" >&2
  fi
}

linked_config() {
  mkdir -p "$1/.config/herdr"
  ln -s /repo/herdr/.config/herdr/config.toml "$1/.config/herdr/config.toml"
}

existing_config_file() {
  mkdir -p "$1/.config/herdr"
  echo 'onboarding = false' > "$1/.config/herdr/config.toml"
}

run_case fresh fresh 0 "tsk setup herdr
stow --dir=$ROOT_DIR --target=$TMP_DIR/home-fresh herdr (dir ready)
herdr plugin install -y smarzban/herdr-file-viewer
tsk setup claude
herdr integration install claude"

run_case rerun done 0 "stow --dir=$ROOT_DIR --target=$TMP_DIR/home-rerun herdr (dir ready)
tsk setup claude" linked_config

run_case tsk-missing tsk-missing 0 "tsk setup herdr
stow --dir=$ROOT_DIR --target=$TMP_DIR/home-tsk-missing herdr (dir ready)
tsk setup claude" linked_config

run_case existing-config fresh 1 "" existing_config_file

if [[ "$failures" -gt 0 ]]; then
  exit 1
fi

echo "herdr-setup tests passed"
